package com.android.tools.idea.rendering.classloading

import androidx.navigationevent.NavigationEventDispatcher
import androidx.navigationevent.NavigationEventDispatcherOwner
import com.android.testutils.TestUtils
import com.android.tools.idea.flags.StudioFlags
import com.android.tools.rendering.classloading.NopClassLocator
import com.android.tools.rendering.classloading.loaders.AsmTransformingLoader
import com.android.tools.rendering.classloading.loaders.ClassLoaderLoader
import com.android.tools.rendering.classloading.loaders.DelegatingClassLoader
import com.android.tools.rendering.classloading.toClassTransform
import org.jetbrains.android.uipreview.createUrlClassLoader
import org.junit.After
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Before
import org.junit.Test

private const val LOADER_WORKSPACE_PATH = "tools/adt/idea/designer/testData/classloader"
private const val CLASSES_TO_LOAD_JAR_NAME = "localnavigationevent.jar"

/**
 * Tests for [LocalNavigationEventTransform].
 *
 * This test verifies that the bytecode transformation correctly intercepts calls to `LocalNavigationEventDispatcherOwner.current` (which
 * maps to `getCurrent`).
 *
 * The transform is expected to:
 * 1. Rename the original `getCurrent` method to `getCurrent_Original`.
 * 2. Generate a new `getCurrent` wrapper method.
 * 3. In the wrapper, call `getCurrent_Original`.
 * 4. If the original returns `null`, the wrapper should return a `FakeNavigationEventDispatcherOwner`.
 * 5. If the original returns a non-null value, the wrapper should return that value.
 *
 * **Note on Implementation:** The test loads `localnavigationevent.jar` from test data. The source for this JAR
 * (`LocalNavigationEventDispatcherOwner.kt`) has been explicitly modified to include `Composer` and `int` parameters on `getCurrent` to
 * mimic the bytecode generated by the `@Composable` annotation, allowing [LocalNavigationEventTransform] to run correctly.
 */
class LocalNavigationEventTransformTest {

  private lateinit var localNavigationEventOwnerClass: Class<*>
  private lateinit var fakeComposer: Any

  @Before
  fun setUp() {
    StudioFlags.COMPOSE_INTERACTIVE_PREVIEW_PREDICTIVE_BACK.override(true)
    val loader = LocalNavigationEventLoader()
    localNavigationEventOwnerClass = loader.loadClass("androidx.navigationevent.compose.LocalNavigationEventDispatcherOwner")
    // We use a FakeComposer loaded from the same classloader as the transformed class.
    // This is necessary because LocalNavigationEventLoader blocks androidx.compose.runtime from the parent to prevent conflicts with the
    // real Compose runtime in the IDE.
    // Using a FakeComposer ensures that the Composer interface matches the one expected by the transformed code (which is the minimal
    // interface defined in our test data), avoiding AbstractMethodErrors.
    fakeComposer = loader.loadClass("androidx.compose.runtime.FakeComposer").getDeclaredConstructor().newInstance()
  }

  @After
  fun tearDown() {
    StudioFlags.COMPOSE_INTERACTIVE_PREVIEW_PREDICTIVE_BACK.clearOverride()
  }

  @Test
  fun `getCurrent_Original doesn't exist when flag is off`() {
    StudioFlags.COMPOSE_INTERACTIVE_PREVIEW_PREDICTIVE_BACK.override(false)
    val localNavigationEventOwnerClass =
      LocalNavigationEventLoader().loadClass("androidx.navigationevent.compose.LocalNavigationEventDispatcherOwner")
    assertNull(localNavigationEventOwnerClass.declaredMethods.firstOrNull { it.name == "getCurrent_Original" })
    StudioFlags.COMPOSE_INTERACTIVE_PREVIEW_PREDICTIVE_BACK.clearOverride()
  }

  @Test
  fun `getCurrent_Original returns null, and getCurrent returns not null`() {
    // Ensure getCurrent_Original returns null
    localNavigationEventOwnerClass.callMethod("setCurrentNavigationEventDispatcherOwner", null)

    // Verify getCurrent_Original exists and returns null
    assertNull(localNavigationEventOwnerClass.callMethod("getCurrent_Original", fakeComposer, 0))

    // Verify getCurrent returns the Fake object because the original returned null
    val getCurrentCall = localNavigationEventOwnerClass.callMethod("getCurrent", fakeComposer, 0)
    assertNotNull(getCurrentCall)
    assertEquals("androidx.navigationevent.compose.FakeNavigationEventDispatcherOwner", getCurrentCall?.javaClass?.name)
  }

  @Test
  fun `getCurrent_Original doesn't return null, then getCurrent() returns the same value as getCurrent_Original`() {
    val navigationEventDispatcherOwner =
      object : NavigationEventDispatcherOwner {
        override val navigationEventDispatcher: NavigationEventDispatcher
          get() = NavigationEventDispatcher()
      }

    // set the NavigationEventDispatcherOwner so getCurrent_Original doesn't return null
    localNavigationEventOwnerClass.callMethod("setCurrentNavigationEventDispatcherOwner", navigationEventDispatcherOwner)

    val getCurrentCall = localNavigationEventOwnerClass.callMethod("getCurrent", fakeComposer, 0)
    val getCurrentOriginalCall = localNavigationEventOwnerClass.callMethod("getCurrent_Original", fakeComposer, 0)

    assertNotNull(getCurrentCall)
    assertNotNull(getCurrentOriginalCall)
    assertEquals(getCurrentCall, getCurrentOriginalCall)

    // The FakeNavigationEventDispatcherOwner is not created.
    assertNotEquals("androidx.navigationevent.compose.FakeNavigationEventDispatcherOwner", getCurrentCall!!.javaClass.name)
    assertNotEquals("androidx.navigationevent.compose.FakeNavigationEventDispatcherOwner", getCurrentOriginalCall!!.javaClass.name)
  }

  @Test
  fun `InteractivePreviewBackNavigationUpdater is updated when getCurrent returns the fake owner`() {
    // Ensure getCurrent_Original returns null
    localNavigationEventOwnerClass.callMethod("setCurrentNavigationEventDispatcherOwner", null)

    // Verify getCurrent returns the Fake object
    val getCurrentCall = localNavigationEventOwnerClass.callMethod("getCurrent", fakeComposer, 0)

    // Verify InteractivePreviewBackNavigationUpdater.lastOwner is set to the same object
    val updaterClass =
      localNavigationEventOwnerClass.classLoader.loadClass(
        "com.android.tools.idea.compose.preview.scene.InteractivePreviewBackNavigationUpdater"
      )
    val lastOwner = updaterClass.callMethod("getLastOwner")

    assertNotNull(getCurrentCall)
    assertEquals("androidx.navigationevent.compose.FakeNavigationEventDispatcherOwner", getCurrentCall?.javaClass?.name)
    assertNotNull(lastOwner)
    assertEquals(getCurrentCall, lastOwner)
  }

  @Test
  fun `InteractivePreviewBackNavigationUpdater is not updated when getCurrent returns the original owner`() {
    val navigationEventDispatcherOwner =
      object : NavigationEventDispatcherOwner {
        override val navigationEventDispatcher: NavigationEventDispatcher
          get() = NavigationEventDispatcher()
      }

    // set the NavigationEventDispatcherOwner so getCurrent_Original doesn't return null
    localNavigationEventOwnerClass.callMethod("setCurrentNavigationEventDispatcherOwner", navigationEventDispatcherOwner)

    val getCurrentCall = localNavigationEventOwnerClass.callMethod("getCurrent", fakeComposer, 0)
    assertNotNull(getCurrentCall)

    // Verify InteractivePreviewBackNavigationUpdater.lastOwner is not set
    val updaterClass =
      localNavigationEventOwnerClass.classLoader.loadClass(
        "com.android.tools.idea.compose.preview.scene.InteractivePreviewBackNavigationUpdater"
      )
    val lastOwner = updaterClass.callMethod("getLastOwner")
    assertNull(lastOwner)
  }

  fun Class<*>.callMethod(methodName: String, vararg arguments: Any?): Any? {
    val instance = this.getField("INSTANCE").get(null)
    return declaredMethods.firstOrNull { it.name == methodName }?.apply { isAccessible = true }?.invoke(instance, *arguments)
  }

  /**
   * A custom class loader that:
   * 1. Loads classes from `localnavigationevent.jar`.
   * 2. Applies `LocalNavigationEventTransform`.
   * 3. Blocks `androidx.compose` from the parent classloader to ensure the dummy version in the JAR is used.
   */
  inner class LocalNavigationEventLoader :
    DelegatingClassLoader(
      object : ClassLoader(this.javaClass.classLoader) {
        override fun loadClass(name: String, resolve: Boolean): Class<*> {
          if (name.startsWith("androidx.compose.runtime")) {
            throw ClassNotFoundException(name)
          }
          return super.loadClass(name, resolve)
        }
      },
      AsmTransformingLoader(
        toClassTransform({ LocalNavigationEventTransform(it) }),
        ClassLoaderLoader(
          createUrlClassLoader(listOf(TestUtils.resolveWorkspacePath(LOADER_WORKSPACE_PATH).resolve(CLASSES_TO_LOAD_JAR_NAME)))
        ),
        NopClassLocator,
      ),
    )
}
