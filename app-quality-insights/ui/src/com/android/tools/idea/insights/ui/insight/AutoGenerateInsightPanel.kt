import kotlinx.coroutines.flow.mapNotNull
import kotlinx.coroutines.flow.stateIn
import kotlinx.coroutines.launch

private const val NO_MODEL_CARD = "NO_MODEL_CARD"
private const val AUTO_GENERATE_DISABLED = "AUTO_GENERATE_DISABLED"

class AutoGenerateInsightPanel(
  private val controller: AppInsightsProjectLevelController,
  private val tracker: AppInsightsTracker,
  parentDisposable: Disposable,
) : JPanel(), Disposable {

  private val autoGenerateDisabledPanel =
    JPanel(HorizontalLayout(JBUI.scale(16))).apply {
      val generateInsight =
        createLink("Generate insight for this issue", Action.GENERATE_ONCE) {
          controller.refreshInsight(regenerateWithContext = false, forceGenerateNewInsight = true)
        }
      val enableAutoGenerate =
        JPanel(HorizontalLayout(JBUI.scale(4))).apply {
          add(
            createLink("Enable auto-generation", Action.ENABLE_AUTO_GENERATE) {
              controller.aiInsightToolkit.setAutoGenerate(true)
              controller.refreshInsight(false)
            }
          )
          add(
            JBLabel(AllIcons.General.Information).apply {
              toolTipText =
                """
                <b>Insight auto-generation</b><br>
                Automatically generate an AI insight for every issue you select using the model selected in the Agent tool window.<br>
                Note: This may increase usage or charges. You can disable this anytime via the gear icon on any generated insight.
                """
                  .trimIndent()
            }
          )
        }

      add(generateInsight)
      add(enableAutoGenerate)
    }

  private val noModelSelectedPanel =
    JPanel(BorderLayout()).apply {
      val label =
        JTextPane().apply {
          foreground = NamedColorUtil.getInactiveTextColor()
          HtmlLabel.setUpAsHtmlLabel(this)
          text = "No AI model selected. Please add or select a model from the Agent tool window and click ‘Regenerate’."
        }
      val regenerateInsight =
        createLink("Regenerate", Action.GENERATE_ONCE) {
          controller.refreshInsight(regenerateWithContext = false, forceGenerateNewInsight = true)
        }
      val actionGroup = DefaultActionGroup(InsightSettingGroup())
      val toolbar = ActionManager.getInstance().createActionToolbar("AutoGenerateInsightPanel", actionGroup, true)
      toolbar.targetComponent = this
      add(label, BorderLayout.NORTH)
      add(regenerateInsight, BorderLayout.WEST)
      add(toolbar.component, BorderLayout.EAST)
    }

  private val scope = createCoroutineScope()
  private val cardLayout = CardLayout()

  private val appIdFlow = controller.state.mapNotNull { it.connections.selected?.appId }.stateIn(scope, SharingStarted.Eagerly, null)

  init {
    Disposer.register(parentDisposable, this)

    layout = cardLayout

    add(noModelSelectedPanel, NO_MODEL_CARD)
    add(autoGenerateDisabledPanel, AUTO_GENERATE_DISABLED)

    scope.launch {
      controller.state
        .map { it.currentInsight }
        .collect {
          when (it) {
            is LoadingState.InsightAutogenerateDisabled -> {
              runInEdt {
                cardLayout.show(this@AutoGenerateInsightPanel, AUTO_GENERATE_DISABLED)
                preferredSize = autoGenerateDisabledPanel.preferredSize
                revalidate()
              }
            }
            is LoadingState.NoModelAvailable -> {
              runInEdt {
                cardLayout.show(this@AutoGenerateInsightPanel, NO_MODEL_CARD)
                preferredSize = noModelSelectedPanel.preferredSize
                revalidate()
              }
            }
            else -> {}
          }
        }
    }
  }

  private fun createLink(text: String, action: Action, onClick: () -> Unit) =
    HyperlinkLabel(text).apply {
      addHyperlinkListener {
        onClick()
        appIdFlow.value?.let { tracker.logGenerateInsightAction(it, action) }
      }
    }

  override fun dispose() = Unit
}
